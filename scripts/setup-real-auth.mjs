// Native, localhost-only bootstrap. The old fixture database is left intact.
import pg from 'pg';
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';

export const nativeRoot=path.join(process.env.LOCALAPPDATA,'MERYO-tests','native-auth');
export const realConfig={host:'127.0.0.1',port:55440,user:'meryo_test_admin',database:'meryo_auth_local',ssl:false};
const ref=JSON.parse(await fs.readFile(new URL('../db/reference/supabase-2026-10-25/schema.json',import.meta.url),'utf8'));
const q=s=>`"${s.replaceAll('"','""')}"`;
export async function secrets(){
 const file=path.join(nativeRoot,'local-secrets.json');
 try{return JSON.parse(await fs.readFile(file,'utf8'));}catch(e){if(e.code!=='ENOENT')throw e;}
 const jwtSecret=crypto.randomBytes(48).toString('hex');
 const header=Buffer.from(JSON.stringify({alg:'HS256',typ:'JWT'})).toString('base64url');
 const payload=Buffer.from(JSON.stringify({role:'anon',iss:'meryo-local',aud:'authenticated',iat:Math.floor(Date.now()/1000),exp:Math.floor(Date.now()/1000)+31536000})).toString('base64url');
 const body=`${header}.${payload}`;
 const data={jwtSecret,anonKey:`${body}.${crypto.createHmac('sha256',jwtSecret).update(body).digest('base64url')}`,authPassword:crypto.randomBytes(32).toString('hex'),restPassword:crypto.randomBytes(32).toString('hex')};
 await fs.mkdir(nativeRoot,{recursive:true});await fs.writeFile(file,JSON.stringify(data),{flag:'wx'});return data;
}
export async function prepareDatabase(){
 const s=await secrets();const admin=new pg.Client({...realConfig,database:'postgres'});await admin.connect();
 try{
  const {rows:[r]}=await admin.query('select host(inet_server_addr()) host,inet_server_port() port');if(r.host!=='127.0.0.1'||r.port!==55440)throw Error('Wrong PostgreSQL destination');
  if(!(await admin.query("select 1 from pg_roles where rolname='postgres'")).rowCount)await admin.query('create role postgres nologin');
  for(const [role,password] of [['meryo_auth_owner',s.authPassword],['meryo_rest_login',s.restPassword]]){
   const exists=(await admin.query('select 1 from pg_roles where rolname=$1',[role])).rowCount;
   if(!exists)await admin.query(`create role ${q(role)} login noinherit password '${password}'`);
  }
  await admin.query('grant anon,authenticated to meryo_rest_login');
  if(!(await admin.query("select 1 from pg_database where datname='meryo_auth_local'")).rowCount)await admin.query('create database meryo_auth_local');
 }finally{await admin.end();}
 const c=new pg.Client(realConfig);await c.connect();try{
  await c.query('create schema if not exists auth authorization meryo_auth_owner');
  await c.query('alter role meryo_auth_owner in database meryo_auth_local set search_path=auth');
  await c.query('grant usage on schema public to meryo_auth_owner');
 }finally{await c.end();}
}
export async function preparePublic(){
 const c=new pg.Client(realConfig);await c.connect();
 try{
  if((await c.query("select to_regclass('public.meryo_native_bootstrap') as marker")).rows[0].marker){
   const version=(await c.query('select version from public.meryo_native_bootstrap')).rows[0].version;
   if(version===2)return;
   throw Error('Incomplete bootstrap marker; stop without overwriting data');
  }
  if((await c.query("select to_regclass('auth.sessions') as sessions")).rows[0].sessions===null)throw Error('Official Auth migrations must finish first');
  if((await c.query("select to_regclass('public.profiles') as profiles")).rows[0].profiles)throw Error('Partial bootstrap detected; preserve data and inspect');
  await c.query('begin');
  await c.query(`create extension if not exists btree_gist with schema public;create extension if not exists "uuid-ossp" with schema public;
   grant usage on schema public,auth to anon,authenticated;
   grant execute on function auth.uid() to anon,authenticated;`);
  for(const table of ref.relations.filter(r=>r.relkind==='r')){
   const columns=ref.columns.filter(x=>x.table_name===table.relname).map(x=>`${q(x.column_name)} ${x.data_type}${x.is_identity==='YES'?' generated by default as identity':x.column_default?` default ${x.column_default}`:''}${x.is_nullable==='NO'?' not null':''}`);
   await c.query(`create table public.${q(table.relname)} (${columns.join(',')})`);
  }
  for(const k of [...ref.constraints].sort((a,b)=>Number(a.definition.startsWith('FOREIGN KEY'))-Number(b.definition.startsWith('FOREIGN KEY'))))await c.query(`alter table public.${q(k.relation.replace('public.',''))} add constraint ${q(k.conname)} ${k.definition}`);
  for(const index of ref.indexes)if(!ref.constraints.some(k=>k.conname===index.indexname))await c.query(index.indexdef);
  await c.query('set local check_function_bodies=off');
  for(const fn of ref.functions)await c.query(fn.definition);
  for(const trigger of ref.triggers)await c.query(trigger.definition);
  for(const table of ref.relations.filter(r=>r.relkind==='r')){
   if(table.relrowsecurity)await c.query(`alter table public.${q(table.relname)} enable row level security`);
   await c.query(`revoke all on public.${q(table.relname)} from public,anon,authenticated,service_role`);
  }
  for(const p of ref.policies.filter(p=>p.schemaname==='public'))await c.query(`create policy ${q(p.policyname)} on public.${q(p.tablename)} as ${p.permissive} for ${p.cmd} to ${p.roles.map(q).join(',')}${p.qual?` using (${p.qual})`:''}${p.with_check?` with check (${p.with_check})`:''}`);
  for(const g of ref.grants.filter(g=>g.table_schema==='public'&&['anon','authenticated','service_role'].includes(g.grantee)))await c.query(`grant ${g.privilege_type} on public.${q(g.table_name)} to ${q(g.grantee)}`);
  for(const g of ref.column_grants.filter(g=>['anon','authenticated','service_role'].includes(g.grantee)))await c.query(`grant ${g.privilege_type} (${q(g.column_name)}) on public.${q(g.table_name)} to ${q(g.grantee)}`);
  for(const fn of ref.functions){await c.query(`revoke all on function public.${fn.signature} from public,anon,authenticated,service_role`);for(const role of ['anon','authenticated','service_role'])if(fn.proacl?.some(a=>a.startsWith(`${role}=X/`)))await c.query(`grant execute on function public.${fn.signature} to ${role}`);}
  // No business rows, fake users or fabricated sessions are inserted.
  await c.query('create table public.meryo_native_bootstrap(version integer not null);insert into public.meryo_native_bootstrap values(1);revoke all on public.meryo_native_bootstrap from public,anon,authenticated;');
  await c.query('commit');
  // Existing approved migrations, only against the NEW local managed-Auth DB.
  for(const file of ['001_privileges_and_payment_lock.sql','002_manual_booking_flow.sql'])await c.query(await fs.readFile(new URL(`../db/incremental/${file}`,import.meta.url),'utf8'));
  await c.query('update public.meryo_native_bootstrap set version=2');
 }catch(e){await c.query('rollback');throw e;}finally{await c.end();}
}
