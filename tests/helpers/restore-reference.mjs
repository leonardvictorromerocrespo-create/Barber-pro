import fs from 'node:fs/promises';

export const reference = JSON.parse(await fs.readFile(new URL('../../db/reference/supabase-2026-10-25/schema.json', import.meta.url), 'utf8'));
const q = s => `"${s.replaceAll('"', '""')}"`;
// Test-only reconstruction. No business rows. Numeric typmods were not in the first
// metadata export, so this fixture cannot certify precision/rounding or Supabase APIs.
export async function restoreReference(c) {
  const { rows: [target] } = await c.query('select current_database() as db, host(inet_server_addr()) as host, inet_server_port() as port');
  if (target.db !== 'meryo_test' || target.host !== '127.0.0.1' || target.port !== 55440) throw Error('Only the dedicated local database is allowed');
  await c.query('drop schema if exists public cascade; drop schema if exists auth cascade; drop schema if exists meryo_private cascade; create schema public; create schema auth;');
  await c.query(`create extension if not exists btree_gist with schema public;
    create extension if not exists "uuid-ossp" with schema public;
    create table auth.users(id uuid primary key, email text, raw_user_meta_data jsonb default '{}');
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    grant usage on schema auth,public to anon,authenticated,service_role;
    grant execute on function auth.uid() to anon,authenticated,service_role;`);
  for (const table of reference.relations.filter(r => r.relkind === 'r')) {
    const columns = reference.columns.filter(x => x.table_name === table.relname).map(x =>
      `${q(x.column_name)} ${x.data_type}${x.is_identity === 'YES' ? ' generated by default as identity' : x.column_default ? ` default ${x.column_default}` : ''}${x.is_nullable === 'NO' ? ' not null' : ''}`);
    await c.query(`create table public.${q(table.relname)} (${columns.join(',')})`);
  }
  for (const k of [...reference.constraints].sort((a,b) => Number(a.definition.startsWith('FOREIGN KEY')) - Number(b.definition.startsWith('FOREIGN KEY')))) {
    await c.query(`alter table public.${q(k.relation.replace('public.', ''))} add constraint ${q(k.conname)} ${k.definition}`);
  }
  for (const index of reference.indexes) {
    if (!reference.constraints.some(k => k.conname === index.indexname)) await c.query(index.indexdef);
  }
  await c.query('set check_function_bodies = off');
  for (const fn of reference.functions) await c.query(fn.definition);
  await c.query('set check_function_bodies = on');
  for (const trigger of reference.triggers) await c.query(trigger.definition);
  for (const table of reference.relations.filter(r => r.relkind === 'r')) {
    if (table.relrowsecurity) await c.query(`alter table public.${q(table.relname)} enable row level security`);
    if (table.relforcerowsecurity) await c.query(`alter table public.${q(table.relname)} force row level security`);
    await c.query(`revoke all on public.${q(table.relname)} from public,anon,authenticated,service_role`);
  }
  for (const p of reference.policies.filter(p => p.schemaname === 'public')) {
    await c.query(`create policy ${q(p.policyname)} on public.${q(p.tablename)} as ${p.permissive} for ${p.cmd} to ${p.roles.map(q).join(',')}${p.qual ? ` using (${p.qual})` : ''}${p.with_check ? ` with check (${p.with_check})` : ''}`);
  }
  for (const g of reference.grants.filter(g => g.table_schema === 'public' && ['anon','authenticated','service_role'].includes(g.grantee))) {
    await c.query(`grant ${g.privilege_type} on public.${q(g.table_name)} to ${q(g.grantee)}`);
  }
  for (const g of reference.column_grants.filter(g => ['anon','authenticated','service_role'].includes(g.grantee))) {
    await c.query(`grant ${g.privilege_type} (${q(g.column_name)}) on public.${q(g.table_name)} to ${q(g.grantee)}`);
  }
  for (const fn of reference.functions) {
    await c.query(`revoke all on function public.${fn.signature} from public,anon,authenticated,service_role`);
    for (const role of ['anon','authenticated','service_role']) if (fn.proacl?.some(a => a.startsWith(`${role}=X/`))) await c.query(`grant execute on function public.${fn.signature} to ${role}`);
  }
}
