import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import pg from 'pg';

// SQL contract checks ONLY in the database restored from the encrypted backup.
// These are synthetic server receipts, not provider charges or an Auth test.
test('restored local database: late/duplicate payment and expiry races',
 {skip:process.env.MERYO_SQL_PAYMENT_TEST!=='1'},async t=>{
 const report=JSON.parse(await fs.readFile(path.join(process.env.LOCALAPPDATA,'MERYO-backups','restore-status.json'),'utf8'));
 if(!/^meryo_restore_\d+$/.test(report.database))throw Error('Refusing any live/demo/production target');
 const config={host:'127.0.0.1',port:55440,user:'meryo_test_admin',database:report.database,ssl:false};
 const db=new pg.Client(config);await db.connect();const ids=[];let settings;
 const server=async(sql,args=[])=>{const c=new pg.Client(config);await c.connect();try{await c.query('set role service_role');return await c.query(sql,args);}finally{await c.end();}};
 try{
  if(!(await db.query("select to_regclass('meryo_private.payment_intents') ready")).rows[0].ready)await db.query(await fs.readFile(new URL('../db/incremental/008_payment_race_gate.sql',import.meta.url),'utf8'));
  settings=(await db.query('select * from meryo_private.launch_settings where id=1')).rows[0];
  await db.query("update meryo_private.launch_settings set pagos_habilitados=true,reservas_habilitadas=true,entorno='staging',plazo_pago_segundos=600 where id=1");
  const person=(await db.query("select id from public.profiles where rol='cliente' and activo limit 1")).rows[0].id;
  const service=(await db.query('select * from public.servicios where activo order by id limit 1')).rows[0];
  const base=Date.now()+5*86400000;let offset=0;
  async function accepted(expired=false,sameStart){
   const id=crypto.randomUUID(),start=sameStart??new Date(base+(offset++)*3600000);ids.push(id);
   await db.query(`insert into public.reservas(id,barberia_id,servicio_id,cliente_id,cliente_nombre,cliente_telefono,servicio_nombre,duracion_min,inicio,fin,precio_total,monto_adelanto,extra_personalizacion,estado,aceptada_en,expira_pago_en)
   values($1,$2,$3,$4,'Contrato SQL aislado','999999999','Fixture de contrato',30,$5,$5::timestamptz+interval '30 minutes',30,15,0,'aceptada',clock_timestamp(),clock_timestamp()+make_interval(secs=>$6))`,[id,service.barberia_id,service.id,person,start,expired?-1:600]);
   // Insert the authoritative intent as the test server; no browser can do this.
   const intent=crypto.randomUUID(),reference=crypto.randomUUID();
   await db.query(`insert into meryo_private.payment_intents(id,reserva_id,proveedor,referencia,merchant_id,monto_centimos,moneda,live,metodo) values($1,$2,'contract-fixture',$3,'merchant-fixture',1500,'PEN',false,'tarjeta')`,[intent,id,reference]);
   return {id,intent,reference,start};
  }
  const pay=r=>server("select public.confirmar_pago_verificado($1,'contract-fixture',$2,'merchant-fixture',1500,'PEN',false) result",[r.intent,r.reference]);
  await t.test('valid server receipt is idempotent; new records have zero per-cut commission',async()=>{
   const r=await accepted();const results=await Promise.all([pay(r),pay(r)]);assert.ok(results.every(x=>x.rows[0].result==='confirmada'));
   const p=(await db.query('select comision_plataforma from public.pagos where reserva_id=$1',[r.id])).rows;assert.equal(p.length,1);assert.equal(Number(p[0].comision_plataforma),0);
  });
  await t.test('late receipt never confirms a slot already released and requested again',async()=>{
   const old=await accepted(true);await db.query("update public.reservas set estado='expirada' where id=$1",[old.id]);
   const next=await accepted(false,old.start);
   assert.equal((await pay(old)).rows[0].result,'requiere_conciliacion');
   assert.equal((await db.query('select estado from public.reservas where id=$1',[old.id])).rows[0].estado,'expirada');
   assert.equal((await db.query('select estado from public.reservas where id=$1',[next.id])).rows[0].estado,'aceptada');
  });
  await t.test('expiry and payment contend for the same row; past-deadline receipt cannot win',async()=>{
   const r=await accepted(true);
   const outcomes=await Promise.all([pay(r),db.query("update public.reservas set estado='expirada',cerrada_en=clock_timestamp() where id=$1 and estado='aceptada' and expira_pago_en<=clock_timestamp()",[r.id])]);
   assert.equal(outcomes[0].rows[0].result,'requiere_conciliacion');
   assert.equal((await db.query('select estado from public.reservas where id=$1',[r.id])).rows[0].estado,'expirada');
   assert.equal((await db.query('select count(*)::int n from public.pagos where reserva_id=$1',[r.id])).rows[0].n,0);
  });
 }finally{
  // Only UUIDs generated by this test in the disposable restore target.
  if(ids.length){await db.query('delete from meryo_private.payment_receipts where intent_id in(select id from meryo_private.payment_intents where reserva_id=any($1::uuid[]))',[ids]);await db.query('delete from public.pagos where reserva_id=any($1::uuid[])',[ids]);await db.query('delete from meryo_private.payment_intents where reserva_id=any($1::uuid[])',[ids]);await db.query('delete from meryo_private.push_outbox where reserva_id=any($1::uuid[])',[ids]);await db.query('delete from public.notificaciones where reserva_id=any($1::uuid[])',[ids]);await db.query('delete from public.reservas where id=any($1::uuid[])',[ids]);}
  if(settings)await db.query('update meryo_private.launch_settings set pagos_habilitados=$1,reservas_habilitadas=$2,entorno=$3,plazo_pago_segundos=$4 where id=1',[settings.pagos_habilitados,settings.reservas_habilitadas,settings.entorno,settings.plazo_pago_segundos]);
  await db.end();
 }
 });
