begin;

-- Pickup-only storefront. A requested order snapshots prices but reserves no
-- stock until the business accepts it. Products are archived, never deleted.
create table public.meryo_products (
 id bigint generated by default as identity primary key,
 barberia_id bigint not null references public.barberias(id) on delete restrict,
 nombre text not null check(length(btrim(nombre)) between 1 and 100),
 descripcion text not null default '' check(length(descripcion)<=1000),
 precio numeric(12,2) not null check(precio>0),
 stock_disponible integer not null default 0 check(stock_disponible>=0),
 foto_path text,
 publicado boolean not null default false,
 archivado_en timestamptz,
 created_at timestamptz not null default clock_timestamp(),
 updated_at timestamptz not null default clock_timestamp(),
 constraint meryo_product_photo_path_check check(foto_path is null or foto_path ~ '^[0-9]+/[0-9a-f-]{36}\.(jpg|jpeg|png|webp)$')
);
create index meryo_products_public_idx on public.meryo_products(barberia_id,nombre)
 where publicado and archivado_en is null;
alter table public.meryo_products enable row level security;
revoke all on public.meryo_products from public,anon,authenticated;
grant select on public.meryo_products to anon,authenticated;
create function public.meryo_products_readable(p_shop bigint,p_published boolean,p_archived timestamptz) returns boolean
language sql stable security definer set search_path='' as $$
 select (auth.uid() is not null and public.meryo_es_propietario(p_shop)) or
  (p_published and p_archived is null and public.meryo_barberia_publicable(p_shop));
$$;
revoke all on function public.meryo_products_readable(bigint,boolean,timestamptz) from public;
grant execute on function public.meryo_products_readable(bigint,boolean,timestamptz) to anon,authenticated;
create policy meryo_products_read on public.meryo_products for select to anon,authenticated using(
 public.meryo_products_readable(barberia_id,publicado,archivado_en)
);

create table public.meryo_pickup_orders (
 id uuid primary key default gen_random_uuid(),
 barberia_id bigint not null references public.barberias(id) on delete restrict,
 cliente_id uuid not null references public.profiles(id) on delete restrict,
 request_key uuid not null,
 estado text not null default 'pendiente' check(estado in ('pendiente','aceptado','rechazado','cancelado','vencido','entregado')),
 total numeric(12,2) not null check(total>0),
 moneda text not null default 'PEN' check(moneda='PEN'),
 recogida_hasta timestamptz,
 estado_stock text not null default 'sin_reserva' check(estado_stock in ('sin_reserva','reservado','liberado','entregado')),
 created_at timestamptz not null default clock_timestamp(),
 updated_at timestamptz not null default clock_timestamp(),
 unique(cliente_id,request_key),
 check((estado='aceptado' and recogida_hasta is not null and estado_stock='reservado') or
       (estado='entregado' and recogida_hasta is not null and estado_stock='entregado') or
       (estado in ('pendiente','rechazado') and recogida_hasta is null and estado_stock='sin_reserva') or
       (estado='cancelado' and ((recogida_hasta is null and estado_stock='sin_reserva') or (recogida_hasta is not null and estado_stock='liberado'))) or
       (estado='vencido' and recogida_hasta is not null and estado_stock='liberado'))
);
create index meryo_pickup_orders_client_idx on public.meryo_pickup_orders(cliente_id,created_at desc);
create index meryo_pickup_orders_shop_idx on public.meryo_pickup_orders(barberia_id,created_at desc);
create index meryo_pickup_orders_expiry_idx on public.meryo_pickup_orders(recogida_hasta,id)
 where estado='aceptado' and estado_stock='reservado';
alter table public.meryo_pickup_orders enable row level security;
revoke all on public.meryo_pickup_orders from public,anon,authenticated;
grant select on public.meryo_pickup_orders to authenticated;
create policy meryo_pickup_orders_read on public.meryo_pickup_orders for select to authenticated using(
 cliente_id=auth.uid() or public.meryo_es_propietario(barberia_id)
);

create table public.meryo_pickup_order_items (
 id bigint generated by default as identity primary key,
 pedido_id uuid not null references public.meryo_pickup_orders(id) on delete restrict,
 producto_id bigint not null references public.meryo_products(id) on delete restrict,
 nombre_snapshot text not null,
 descripcion_snapshot text not null,
 precio_snapshot numeric(12,2) not null check(precio_snapshot>0),
 foto_path_snapshot text,
 cantidad integer not null check(cantidad between 1 and 99),
 subtotal numeric(12,2) not null check(subtotal>0),
 unique(pedido_id,producto_id)
);
create index meryo_pickup_items_order_idx on public.meryo_pickup_order_items(pedido_id,id);
alter table public.meryo_pickup_order_items enable row level security;
revoke all on public.meryo_pickup_order_items from public,anon,authenticated;
grant select on public.meryo_pickup_order_items to authenticated;
create policy meryo_pickup_items_read on public.meryo_pickup_order_items for select to authenticated using(
 exists(select 1 from public.meryo_pickup_orders o where o.id=pedido_id and
  (o.cliente_id=auth.uid() or public.meryo_es_propietario(o.barberia_id)))
);

alter table public.notificaciones add column pedido_id uuid references public.meryo_pickup_orders(id) on delete restrict;
alter table meryo_private.push_outbox add column pedido_id uuid references public.meryo_pickup_orders(id) on delete restrict;
create index meryo_push_outbox_order_idx on meryo_private.push_outbox(pedido_id) where pedido_id is not null;

create or replace function meryo_private.notify_pickup_order(p_user uuid,p_order uuid,p_event text)
returns void language plpgsql security definer set search_path='' as $$
declare title text;body text;begin
 if p_user is null or p_event not in ('pedido_solicitado','pedido_aceptado','pedido_rechazado','pedido_cancelado','pedido_vencido') then
  raise exception 'Notificación de pedido inválida';
 end if;
 title:=case p_event when 'pedido_solicitado' then 'Nueva solicitud para recoger'
  when 'pedido_aceptado' then 'Solicitud de recojo aceptada'
  when 'pedido_rechazado' then 'Solicitud de recojo rechazada'
  when 'pedido_cancelado' then 'Pedido cancelado' else 'Plazo de recojo vencido' end;
 body:=case p_event when 'pedido_solicitado' then 'Hay una nueva solicitud de productos pendiente de disponibilidad.'
  when 'pedido_aceptado' then 'Tu solicitud fue aceptada. Pagas al recoger en la barbería.'
  when 'pedido_rechazado' then 'La barbería no pudo aceptar tu solicitud. No se reservó stock.'
  when 'pedido_cancelado' then case when exists(select 1 from public.meryo_pickup_orders o where o.id=p_order and o.estado_stock='liberado') then 'La barbería canceló el pedido y liberó las unidades reservadas.' else 'La barbería canceló la solicitud antes de reservar unidades.' end
  else 'El plazo de recojo terminó y las unidades volvieron al stock.' end;
 insert into public.notificaciones(user_id,titulo,mensaje,tipo,pedido_id)
 values(p_user,title,body,p_event,p_order);
end;$$;
revoke all on function meryo_private.notify_pickup_order(uuid,uuid,text) from public,anon,authenticated,service_role;

create or replace function meryo_private.queue_push() returns trigger
language plpgsql security definer set search_path='' as $$begin
 if new.tipo in ('reserva_solicitada','reserva_aceptada','reserva_rechazada','reserva_expirada','reserva_confirmada','push_diagnostico') then
  insert into meryo_private.push_outbox(notification_id,user_id,event,reserva_id,pedido_id,available_at)
  values(new.id,new.user_id,new.tipo,new.reserva_id,null,clock_timestamp()+case when new.tipo='push_diagnostico' then interval '30 seconds' else interval '0 seconds' end);
 elsif new.tipo in ('pedido_solicitado','pedido_aceptado','pedido_rechazado','pedido_cancelado','pedido_vencido') then
  insert into meryo_private.push_outbox(notification_id,user_id,event,reserva_id,pedido_id,available_at)
  values(new.id,new.user_id,new.tipo,null,new.pedido_id,clock_timestamp());
 end if;
 return new;
end;$$;
revoke all on function meryo_private.queue_push() from public,anon,authenticated,service_role;

create or replace function public.meryo_save_product(p_id bigint,p_data jsonb) returns bigint
language plpgsql security definer set search_path='' as $$
declare shop bigint:=public.mi_barberia_id();uid uuid:=auth.uid();v_name text;v_description text;v_price numeric;v_stock integer;v_published boolean;v_photo text;result bigint;meta jsonb;owner_text text;
begin
 if not public.meryo_cuenta_activa() or not public.meryo_es_propietario(shop) then raise exception 'Solo el propietario activo puede administrar productos' using errcode='42501';end if;
 if jsonb_typeof(p_data)<>'object' then raise exception 'Datos de producto inválidos';end if;
 v_name:=btrim(coalesce(p_data->>'nombre',''));v_description:=coalesce(p_data->>'descripcion','');
 v_price:=(p_data->>'precio')::numeric;v_stock:=(p_data->>'stock_disponible')::integer;
 v_published:=coalesce((p_data->>'publicado')::boolean,false);v_photo:=nullif(p_data->>'foto_path','');
 if length(v_name) not between 1 and 100 or length(v_description)>1000 or v_price<=0 or v_stock<0 then raise exception 'Revisa nombre, descripción, precio y stock';end if;
 if v_published and v_photo is null then raise exception 'Añade una fotografía antes de publicar el producto';end if;
 if v_photo is not null then
  if split_part(v_photo,'/',1)<>shop::text or v_photo !~ '^[0-9]+/[0-9a-f-]{36}\.(jpg|jpeg|png|webp)$' then raise exception 'La fotografía no pertenece a esta barbería';end if;
  select metadata,owner_id into meta,owner_text from storage.objects where bucket_id='meryo-shop-content' and name=v_photo for share;
  if not found or owner_text is distinct from uid::text or coalesce(meta->>'mimetype','') not in ('image/jpeg','image/png','image/webp') or coalesce((meta->>'size')::bigint,0) not between 1 and 5242880 then raise exception 'La fotografía no existe, no es válida o no fue subida por esta cuenta';end if;
 end if;
 if p_id is null then
  insert into public.meryo_products(barberia_id,nombre,descripcion,precio,stock_disponible,foto_path,publicado)
  values(shop,v_name,v_description,v_price,v_stock,v_photo,v_published) returning id into result;
 else
  update public.meryo_products set nombre=v_name,descripcion=v_description,precio=v_price,stock_disponible=v_stock,
   foto_path=v_photo,publicado=v_published,updated_at=clock_timestamp()
  where id=p_id and barberia_id=shop and archivado_en is null returning id into result;
  if result is null then raise exception 'Producto no encontrado o archivado';end if;
 end if;
 return result;
end;$$;
revoke all on function public.meryo_save_product(bigint,jsonb) from public,anon;
grant execute on function public.meryo_save_product(bigint,jsonb) to authenticated;

create function public.meryo_archive_product(p_id bigint) returns boolean
language plpgsql security definer set search_path='' as $$
declare shop bigint:=public.mi_barberia_id();begin
 if not public.meryo_cuenta_activa() or not public.meryo_es_propietario(shop) then raise exception 'Solo el propietario activo puede archivar productos' using errcode='42501';end if;
 update public.meryo_products set publicado=false,archivado_en=coalesce(archivado_en,clock_timestamp()),updated_at=clock_timestamp()
 where id=p_id and barberia_id=shop;
 if not found then raise exception 'Producto no encontrado';end if;return true;
end;$$;
revoke all on function public.meryo_archive_product(bigint) from public,anon;
grant execute on function public.meryo_archive_product(bigint) to authenticated;

create function public.meryo_request_pickup(p_shop bigint,p_items jsonb,p_request_key uuid) returns uuid
language plpgsql security definer set search_path='' as $$
declare uid uuid:=auth.uid();shoprow public.barberias%rowtype;productrow record;existing uuid;result uuid;total_amount numeric(12,2):=0;line_count integer;
begin
 if not public.meryo_cuenta_activa() or not exists(select 1 from public.profiles where id=uid and rol='cliente') then raise exception 'Inicia sesión con una cuenta de cliente activa' using errcode='42501';end if;
 if p_request_key is null or jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items) not between 1 and 20 then raise exception 'Selecciona entre uno y veinte productos';end if;
 if exists(select 1 from jsonb_array_elements(p_items) x(item) where coalesce(x.item->>'product_id','') !~ '^\d+$' or coalesce(x.item->>'quantity','') !~ '^[1-9]\d{0,1}$') then raise exception 'Producto o cantidad inválidos';end if;
 if (select count(*) from jsonb_array_elements(p_items))<>(select count(distinct (x.item->>'product_id')::bigint) from jsonb_array_elements(p_items) x(item)) then raise exception 'No repitas productos en la misma solicitud';end if;
 perform pg_advisory_xact_lock(hashtextextended('meryo-pickup-key-'||uid::text||':'||p_request_key::text,0));
 select id into existing from public.meryo_pickup_orders where cliente_id=uid and request_key=p_request_key;
 if existing is not null then return existing;end if;
 select * into shoprow from public.barberias where id=p_shop and public.meryo_barberia_publicable(id) for share;
 if not found then raise exception 'Esta barbería no está visible para solicitudes';end if;
 for productrow in
  select p.id,p.nombre,p.descripcion,p.precio,p.stock_disponible,p.foto_path,(x.item->>'quantity')::integer quantity
  from jsonb_array_elements(p_items) x(item) join public.meryo_products p on p.id=(x.item->>'product_id')::bigint
  where p.barberia_id=p_shop and p.publicado and p.archivado_en is null order by p.id
  for share of p
 loop
  total_amount:=total_amount+productrow.precio*productrow.quantity;
 end loop;
 select count(*) into line_count from jsonb_array_elements(p_items);
 if (select count(*) from public.meryo_products p join jsonb_array_elements(p_items) x(item) on p.id=(x.item->>'product_id')::bigint where p.barberia_id=p_shop and p.publicado and p.archivado_en is null)<>line_count then
  raise exception 'Un producto ya no está publicado en esta barbería. Revisa la selección.';
 end if;
 if total_amount<=0 then raise exception 'No se pudo calcular el total de la solicitud';end if;
 insert into public.meryo_pickup_orders(barberia_id,cliente_id,request_key,total) values(p_shop,uid,p_request_key,total_amount) returning id into result;
 insert into public.meryo_pickup_order_items(pedido_id,producto_id,nombre_snapshot,descripcion_snapshot,precio_snapshot,foto_path_snapshot,cantidad,subtotal)
 select result,p.id,p.nombre,p.descripcion,p.precio,p.foto_path,(x.item->>'quantity')::integer,p.precio*(x.item->>'quantity')::integer
 from jsonb_array_elements(p_items) x(item) join public.meryo_products p on p.id=(x.item->>'product_id')::bigint
 where p.barberia_id=p_shop and p.publicado and p.archivado_en is null order by p.id;
 perform meryo_private.notify_pickup_order(o.user_id,result,'pedido_solicitado') from meryo_private.shop_owners o where o.barberia_id=p_shop;
 return result;
end;$$;
revoke all on function public.meryo_request_pickup(bigint,jsonb,uuid) from public,anon;
grant execute on function public.meryo_request_pickup(bigint,jsonb,uuid) to authenticated;

create function meryo_private.accept_pickup_order(p_id uuid,p_deadline timestamptz) returns text
language plpgsql security definer set search_path='' as $$
declare o public.meryo_pickup_orders%rowtype;item record;
begin
 select * into o from public.meryo_pickup_orders where id=p_id for update;
 if not found then raise exception 'Solicitud no encontrada';end if;
 if not public.meryo_es_propietario(o.barberia_id) then raise exception 'Solo el propietario de esta barbería puede responder' using errcode='42501';end if;
 if o.estado<>'pendiente' then raise exception 'La solicitud ya no está pendiente';end if;
 if not public.meryo_barberia_publicable(o.barberia_id) then raise exception 'La barbería ya no está visible y no puede aceptar nuevos pedidos';end if;
 if p_deadline is null or p_deadline<=clock_timestamp() then raise exception 'El plazo de recojo debe estar en el futuro';end if;
 perform p.id from public.meryo_products p join public.meryo_pickup_order_items i on i.producto_id=p.id
 where i.pedido_id=p_id order by p.id for update of p;
 if exists(select 1 from public.meryo_pickup_order_items i left join public.meryo_products p on p.id=i.producto_id
  where i.pedido_id=p_id and (p.id is null or p.barberia_id<>o.barberia_id or not p.publicado or p.archivado_en is not null or p.precio<>i.precio_snapshot)) then
  raise exception 'No se puede aceptar: algún producto cambió de precio o ya no está publicado. La solicitud sigue pendiente; crea una nueva selección.';
 end if;
 if exists(select 1 from public.meryo_pickup_order_items i join public.meryo_products p on p.id=i.producto_id where i.pedido_id=p_id and p.stock_disponible<i.cantidad) then
  raise exception 'No hay unidades suficientes para completar todo el pedido. No se reservó stock y la solicitud sigue pendiente.';
 end if;
 for item in select producto_id,cantidad from public.meryo_pickup_order_items where pedido_id=p_id order by producto_id loop
  update public.meryo_products set stock_disponible=stock_disponible-item.cantidad,updated_at=clock_timestamp() where id=item.producto_id;
 end loop;
 update public.meryo_pickup_orders set estado='aceptado',recogida_hasta=p_deadline,estado_stock='reservado',updated_at=clock_timestamp() where id=p_id;
 perform meryo_private.notify_pickup_order(o.cliente_id,p_id,'pedido_aceptado');return 'aceptado';
end;$$;
revoke all on function meryo_private.accept_pickup_order(uuid,timestamptz) from public,anon,authenticated,service_role;

create function public.meryo_accept_pickup_order(p_id uuid,p_deadline timestamptz) returns text
language plpgsql security definer set search_path='' as $$begin return meryo_private.accept_pickup_order(p_id,p_deadline);end;$$;
revoke all on function public.meryo_accept_pickup_order(uuid,timestamptz) from public,anon;
grant execute on function public.meryo_accept_pickup_order(uuid,timestamptz) to authenticated;

