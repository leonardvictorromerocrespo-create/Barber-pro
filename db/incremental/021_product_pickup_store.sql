create function meryo_private.release_pickup_stock(p_id uuid) returns void
language plpgsql security definer set search_path='' as $$declare item record;begin
 for item in select producto_id,cantidad from public.meryo_pickup_order_items where pedido_id=p_id order by producto_id loop
  update public.meryo_products set stock_disponible=stock_disponible+item.cantidad,updated_at=clock_timestamp() where id=item.producto_id;
 end loop;
end;$$;
revoke all on function meryo_private.release_pickup_stock(uuid) from public,anon,authenticated,service_role;

create function meryo_private.expire_pickup_orders() returns integer
language plpgsql security definer set search_path='' as $$declare item record;changed integer:=0;begin
 for item in select id,cliente_id from public.meryo_pickup_orders where estado='aceptado' and estado_stock='reservado' and recogida_hasta<=clock_timestamp() order by recogida_hasta,id for update skip locked limit 100 loop
  perform meryo_private.release_pickup_stock(item.id);
  update public.meryo_pickup_orders set estado='vencido',estado_stock='liberado',updated_at=clock_timestamp() where id=item.id and estado='aceptado' and estado_stock='reservado';
  if found then perform meryo_private.notify_pickup_order(item.cliente_id,item.id,'pedido_vencido');changed:=changed+1;end if;
 end loop;return changed;end;$$;
revoke all on function meryo_private.expire_pickup_orders() from public,anon,authenticated,service_role;

create function public.meryo_cancel_pickup_order(p_id uuid) returns text
language plpgsql security definer set search_path='' as $$declare o public.meryo_pickup_orders%rowtype;begin
 select * into o from public.meryo_pickup_orders where id=p_id for update;
 if not found then raise exception 'Pedido no encontrado';end if;
 if not public.meryo_es_propietario(o.barberia_id) then raise exception 'Solo el propietario de esta barbería puede cancelar' using errcode='42501';end if;
 if o.estado in ('cancelado','vencido','rechazado') then return o.estado;end if;
 if o.estado='entregado' then raise exception 'Un pedido entregado no se puede cancelar';end if;
 if o.estado_stock='reservado' then perform meryo_private.release_pickup_stock(p_id);end if;
 update public.meryo_pickup_orders set estado='cancelado',estado_stock=case when estado_stock='reservado' then 'liberado' else 'sin_reserva' end,updated_at=clock_timestamp() where id=p_id;
 perform meryo_private.notify_pickup_order(o.cliente_id,p_id,'pedido_cancelado');return 'cancelado';end;$$;
revoke all on function public.meryo_cancel_pickup_order(uuid) from public,anon;
grant execute on function public.meryo_cancel_pickup_order(uuid) to authenticated;

create function public.meryo_deliver_pickup_order(p_id uuid) returns text
language plpgsql security definer set search_path='' as $$declare o public.meryo_pickup_orders%rowtype;begin
 select * into o from public.meryo_pickup_orders where id=p_id for update;
 if not found then raise exception 'Pedido no encontrado';end if;
 if not public.meryo_es_propietario(o.barberia_id) then raise exception 'Solo el propietario de esta barbería puede registrar la entrega' using errcode='42501';end if;
 if o.estado='aceptado' and o.estado_stock='reservado' and o.recogida_hasta<=clock_timestamp() then
  perform meryo_private.release_pickup_stock(p_id);
  update public.meryo_pickup_orders set estado='vencido',estado_stock='liberado',updated_at=clock_timestamp() where id=p_id;
  perform meryo_private.notify_pickup_order(o.cliente_id,p_id,'pedido_vencido');return 'vencido';
 end if;
 if o.estado<>'aceptado' or o.estado_stock<>'reservado' then raise exception 'El pedido ya no está disponible para entrega';end if;
 update public.meryo_pickup_orders set estado='entregado',estado_stock='entregado',updated_at=clock_timestamp() where id=p_id;
 return 'entregado';end;$$;
revoke all on function public.meryo_deliver_pickup_order(uuid) from public,anon;
grant execute on function public.meryo_deliver_pickup_order(uuid) to authenticated;

create function public.meryo_pickup_orders(p_id uuid default null) returns jsonb
language plpgsql security definer set search_path='' as $$declare uid uuid:=auth.uid();role_name text;result jsonb;begin
 if not public.meryo_cuenta_activa() then raise exception 'Inicia sesión con una cuenta activa' using errcode='42501';end if;
 select rol into role_name from public.profiles where id=uid;
 if role_name not in ('cliente','barbero') then raise exception 'Esta cuenta no puede consultar pedidos' using errcode='42501';end if;
 if role_name='barbero' and not exists(select 1 from meryo_private.shop_owners where user_id=uid) then raise exception 'Solo el propietario administra pedidos' using errcode='42501';end if;
 perform meryo_private.expire_pickup_orders();
 select coalesce(jsonb_agg(to_jsonb(o)||jsonb_build_object(
  'barberias',jsonb_build_object('nombre',b.nombre,'direccion',b.direccion),
